import { Button } from "@/components/ui/button";
import { FileSpreadsheet, FileText } from "lucide-react";

interface TableColumn {
  header: string;
  key: string;
  align?: "left" | "right" | "center";
}

interface TableDownloadProps {
  data: Record<string, unknown>[];
  columns: TableColumn[];
  filename: string;
}

export function TableDownload({ data, columns, filename }: TableDownloadProps) {
  const downloadExcel = async () => {
    const XLSX = await import("xlsx");
    const rows = data.map((row) => {
      const obj: Record<string, unknown> = {};
      columns.forEach((col) => {
        obj[col.header] = row[col.key];
      });
      return obj;
    });
    const ws = XLSX.utils.json_to_sheet(rows);

    const colWidths = columns.map((col) => {
      const maxLen = Math.max(
        col.header.length,
        ...data.map((row) => String(row[col.key] ?? "").length)
      );
      return { wch: Math.min(maxLen + 4, 40) };
    });
    ws["!cols"] = colWidths;

    const wb = XLSX.utils.book_new();
    XLSX.utils.book_append_sheet(wb, ws, "Data");
    XLSX.writeFile(wb, `${filename}.xlsx`);
  };

  const downloadWord = async () => {
    const docx = await import("docx");
    const { saveAs } = await import("file-saver");

    const headerRow = new docx.TableRow({
      tableHeader: true,
      children: columns.map(
        (col) =>
          new docx.TableCell({
            shading: { fill: "2d3748", type: docx.ShadingType.CLEAR },
            children: [
              new docx.Paragraph({
                alignment:
                  col.align === "right"
                    ? docx.AlignmentType.RIGHT
                    : col.align === "center"
                      ? docx.AlignmentType.CENTER
                      : docx.AlignmentType.LEFT,
                children: [
                  new docx.TextRun({
                    text: col.header,
                    bold: true,
                    color: "ffffff",
                    font: "Calibri",
                    size: 20,
                  }),
                ],
              }),
            ],
            verticalAlign: docx.VerticalAlign.CENTER,
          })
      ),
    });

    const dataRows = data.map(
      (row, idx) =>
        new docx.TableRow({
          children: columns.map(
            (col) =>
              new docx.TableCell({
                shading:
                  idx % 2 === 0
                    ? { fill: "f7fafc", type: docx.ShadingType.CLEAR }
                    : undefined,
                children: [
                  new docx.Paragraph({
                    alignment:
                      col.align === "right"
                        ? docx.AlignmentType.RIGHT
                        : col.align === "center"
                          ? docx.AlignmentType.CENTER
                          : docx.AlignmentType.LEFT,
                    children: [
                      new docx.TextRun({
                        text: String(row[col.key] ?? ""),
                        font: "Calibri",
                        size: 19,
                      }),
                    ],
                  }),
                ],
                verticalAlign: docx.VerticalAlign.CENTER,
              })
          ),
        })
    );

    const table = new docx.Table({
      rows: [headerRow, ...dataRows],
      width: { size: 100, type: docx.WidthType.PERCENTAGE },
    });

    const doc = new docx.Document({
      sections: [
        {
          children: [
            new docx.Paragraph({
              children: [
                new docx.TextRun({
                  text: filename,
                  bold: true,
                  font: "Calibri",
                  size: 28,
                }),
              ],
              spacing: { after: 200 },
            }),
            table,
            new docx.Paragraph({
              children: [
                new docx.TextRun({
                  text: `Generated by Traduxa · ${new Date().toLocaleDateString()}`,
                  font: "Calibri",
                  size: 16,
                  italics: true,
                  color: "888888",
                }),
              ],
              spacing: { before: 300 },
            }),
          ],
        },
      ],
    });

    const blob = await docx.Packer.toBlob(doc);
    saveAs(blob, `${filename}.docx`);
  };

  if (data.length === 0) return null;

  return (
    <div className="flex gap-1.5" data-testid="table-download-buttons">
      <Button
        variant="ghost"
        size="sm"
        className="h-7 text-xs gap-1.5 text-muted-foreground hover:text-foreground"
        onClick={downloadExcel}
        data-testid="button-download-excel"
      >
        <FileSpreadsheet className="w-3.5 h-3.5" />
        Excel
      </Button>
      <Button
        variant="ghost"
        size="sm"
        className="h-7 text-xs gap-1.5 text-muted-foreground hover:text-foreground"
        onClick={downloadWord}
        data-testid="button-download-word"
      >
        <FileText className="w-3.5 h-3.5" />
        Word
      </Button>
    </div>
  );
}
