import { useRef, useCallback } from "react";
import ReactMarkdown from "react-markdown";
import remarkGfm from "remark-gfm";
import { Button } from "@/components/ui/button";
import { FileSpreadsheet, FileText } from "lucide-react";

interface MarkdownRenderProps {
  content: string;
  className?: string;
  showDownload?: boolean;
  downloadFilename?: string;
}

function parseMarkdownTables(markdown: string): { headers: string[]; rows: string[][] }[] {
  const tables: { headers: string[]; rows: string[][] }[] = [];
  const lines = markdown.split("\n");
  let i = 0;
  while (i < lines.length) {
    const line = lines[i].trim();
    if (line.startsWith("|") && line.endsWith("|")) {
      const headerLine = line;
      const separatorLine = (lines[i + 1] || "").trim();
      if (separatorLine.startsWith("|") && separatorLine.includes("-")) {
        const headers = headerLine.split("|").filter(Boolean).map(s => s.trim());
        const rows: string[][] = [];
        let j = i + 2;
        while (j < lines.length) {
          const rowLine = lines[j].trim();
          if (!rowLine.startsWith("|") || !rowLine.endsWith("|")) break;
          rows.push(rowLine.split("|").filter(Boolean).map(s => s.trim()));
          j++;
        }
        if (rows.length > 0) {
          tables.push({ headers, rows });
        }
        i = j;
        continue;
      }
    }
    i++;
  }
  return tables;
}

async function downloadExcel(tables: { headers: string[]; rows: string[][] }[], filename: string) {
  const XLSX = await import("xlsx");
  const wb = XLSX.utils.book_new();
  tables.forEach((table, idx) => {
    const sheetData = [table.headers, ...table.rows];
    const ws = XLSX.utils.aoa_to_sheet(sheetData);
    ws["!cols"] = table.headers.map((h, ci) => {
      const maxLen = Math.max(h.length, ...table.rows.map(r => (r[ci] || "").length));
      return { wch: Math.min(maxLen + 4, 50) };
    });
    XLSX.utils.book_append_sheet(wb, ws, tables.length > 1 ? `Table ${idx + 1}` : "Data");
  });
  XLSX.writeFile(wb, `${filename}.xlsx`);
}

async function downloadWord(tables: { headers: string[]; rows: string[][] }[], filename: string) {
  const docx = await import("docx");
  const { saveAs } = await import("file-saver");

  const docTables = tables.map((table) => {
    const headerRow = new docx.TableRow({
      tableHeader: true,
      children: table.headers.map(h =>
        new docx.TableCell({
          shading: { fill: "2d3748", type: docx.ShadingType.CLEAR },
          children: [new docx.Paragraph({
            children: [new docx.TextRun({ text: h, bold: true, color: "ffffff", font: "Calibri", size: 20 })],
          })],
          verticalAlign: docx.VerticalAlign.CENTER,
        })
      ),
    });

    const dataRows = table.rows.map((row, idx) =>
      new docx.TableRow({
        children: table.headers.map((_, ci) =>
          new docx.TableCell({
            shading: idx % 2 === 0 ? { fill: "f7fafc", type: docx.ShadingType.CLEAR } : undefined,
            children: [new docx.Paragraph({
              children: [new docx.TextRun({ text: row[ci] || "", font: "Calibri", size: 19 })],
            })],
            verticalAlign: docx.VerticalAlign.CENTER,
          })
        ),
      })
    );

    return new docx.Table({
      rows: [headerRow, ...dataRows],
      width: { size: 100, type: docx.WidthType.PERCENTAGE },
    });
  });

  const children: (typeof docx.Paragraph.prototype | typeof docx.Table.prototype)[] = [
    new docx.Paragraph({
      children: [new docx.TextRun({ text: filename, bold: true, font: "Calibri", size: 28 })],
      spacing: { after: 200 },
    }),
  ];
  docTables.forEach((t, i) => {
    if (i > 0) {
      children.push(new docx.Paragraph({ children: [], spacing: { before: 300 } }));
    }
    children.push(t as any);
  });
  children.push(
    new docx.Paragraph({
      children: [new docx.TextRun({
        text: `Generated by Traduxa · ${new Date().toLocaleDateString()}`,
        font: "Calibri", size: 16, italics: true, color: "888888",
      })],
      spacing: { before: 300 },
    })
  );

  const doc = new docx.Document({ sections: [{ children: children as any[] }] });
  const blob = await docx.Packer.toBlob(doc);
  saveAs(blob, `${filename}.docx`);
}

export function MarkdownRender({ content, className = "", showDownload = true, downloadFilename = "AI_Results" }: MarkdownRenderProps) {
  const tables = parseMarkdownTables(content);
  const hasTable = tables.length > 0;

  return (
    <div className={`space-y-3 ${className}`}>
      {hasTable && showDownload && (
        <div className="flex justify-end gap-1.5" data-testid="ai-table-download-buttons">
          <Button
            variant="ghost"
            size="sm"
            className="h-7 text-xs gap-1.5 text-muted-foreground hover:text-foreground"
            onClick={() => downloadExcel(tables, downloadFilename)}
            data-testid="button-ai-download-excel"
          >
            <FileSpreadsheet className="w-3.5 h-3.5" />
            Excel
          </Button>
          <Button
            variant="ghost"
            size="sm"
            className="h-7 text-xs gap-1.5 text-muted-foreground hover:text-foreground"
            onClick={() => downloadWord(tables, downloadFilename)}
            data-testid="button-ai-download-word"
          >
            <FileText className="w-3.5 h-3.5" />
            Word
          </Button>
        </div>
      )}
      <div className="prose prose-sm dark:prose-invert max-w-none markdown-content" data-testid="text-markdown-content">
        <ReactMarkdown
          remarkPlugins={[remarkGfm]}
          components={{
            table: ({ children }) => (
              <div className="overflow-x-auto rounded-lg border border-border/60 my-4">
                <table className="w-full text-sm border-collapse min-w-[400px]">
                  {children}
                </table>
              </div>
            ),
            thead: ({ children }) => (
              <thead className="bg-muted/60 dark:bg-muted/30">
                {children}
              </thead>
            ),
            th: ({ children }) => (
              <th className="py-2.5 px-3 text-left text-[11px] font-semibold uppercase tracking-wider text-foreground/80 border-b border-border/60 whitespace-nowrap">
                {children}
              </th>
            ),
            td: ({ children }) => (
              <td className="py-2 px-3 text-sm border-b border-border/30 text-foreground/90">
                {children}
              </td>
            ),
            tr: ({ children }) => (
              <tr className="hover:bg-muted/20 transition-colors">
                {children}
              </tr>
            ),
            strong: ({ children }) => (
              <strong className="font-semibold text-foreground">{children}</strong>
            ),
            h1: ({ children }) => (
              <h1 className="text-xl font-bold mt-5 mb-3 text-foreground">{children}</h1>
            ),
            h2: ({ children }) => (
              <h2 className="text-lg font-bold mt-4 mb-2 text-foreground">{children}</h2>
            ),
            h3: ({ children }) => (
              <h3 className="text-base font-semibold mt-3 mb-2 text-foreground">{children}</h3>
            ),
            p: ({ children }) => (
              <p className="text-sm leading-relaxed text-foreground/85 mb-3">{children}</p>
            ),
            ul: ({ children }) => (
              <ul className="list-disc pl-5 space-y-1 text-sm text-foreground/85 mb-3">{children}</ul>
            ),
            ol: ({ children }) => (
              <ol className="list-decimal pl-5 space-y-1 text-sm text-foreground/85 mb-3">{children}</ol>
            ),
            li: ({ children }) => (
              <li className="leading-relaxed">{children}</li>
            ),
          }}
        >
          {content}
        </ReactMarkdown>
      </div>
    </div>
  );
}
