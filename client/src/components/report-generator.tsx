import { useState } from "react";
import { Button } from "@/components/ui/button";
import { FileText, FileDown, Loader2 } from "lucide-react";
import type { CorpusStats, KeywordResult, NgramResult, CollocationResult, AlignedPair } from "@shared/schema";

interface ReportGeneratorProps {
  title?: string;
  stats?: CorpusStats | null;
  keywords?: KeywordResult[];
  collocations?: CollocationResult[];
  ngrams?: NgramResult[];
  aiResults?: Record<string, string>;
  pairs?: AlignedPair[];
  extraSections?: { heading: string; content: string }[];
}

function buildReportMarkdown({
  title = "Corpus Analysis Report",
  stats,
  keywords,
  collocations,
  ngrams,
  aiResults,
  pairs,
  extraSections,
}: ReportGeneratorProps): string {
  const lines: string[] = [];

  lines.push(`# ${title}`);
  lines.push("");
  lines.push(`*Generated by Traduxa on ${new Date().toLocaleDateString("en-US", { year: "numeric", month: "long", day: "numeric" })}*`);
  lines.push("");
  lines.push("---");
  lines.push("");

  if (stats) {
    lines.push("## Corpus Statistics");
    lines.push("");
    lines.push("| Metric | Value |");
    lines.push("| --- | --- |");
    lines.push(`| Characters | ${stats.characters.toLocaleString()} |`);
    lines.push(`| Words | ${stats.words.toLocaleString()} |`);
    lines.push(`| Unique Words | ${stats.uniqueWords.toLocaleString()} |`);
    lines.push(`| Sentences | ${stats.sentences.toLocaleString()} |`);
    lines.push(`| Type-Token Ratio | ${stats.typeTokenRatio.toFixed(4)} |`);
    lines.push(`| Avg Words/Sentence | ${stats.avgWordsPerSentence} |`);
    lines.push("");
  }

  if (keywords && keywords.length > 0) {
    lines.push("## Keywords");
    lines.push("");
    lines.push("| Rank | Term | Frequency |");
    lines.push("| --- | --- | --- |");
    keywords.forEach((kw, i) => {
      lines.push(`| ${i + 1} | ${kw.term} | ${kw.frequency.toLocaleString()} |`);
    });
    lines.push("");
  }

  if (collocations && collocations.length > 0) {
    lines.push("## Collocations");
    lines.push("");
    lines.push("| Collocate | Frequency | MI | Dice |");
    lines.push("| --- | --- | --- | --- |");
    collocations.forEach((c) => {
      lines.push(`| ${c.collocate} | ${c.frequency} | ${c.mi.toFixed(2)} | ${c.dice.toFixed(3)} |`);
    });
    lines.push("");
  }

  if (ngrams && ngrams.length > 0) {
    lines.push("## N-grams");
    lines.push("");
    lines.push("| N-gram | Frequency |");
    lines.push("| --- | --- |");
    ngrams.forEach((ng) => {
      lines.push(`| ${ng.ngram} | ${ng.frequency.toLocaleString()} |`);
    });
    lines.push("");
  }

  if (pairs && pairs.length > 0) {
    lines.push("## Aligned Pairs");
    lines.push("");
    lines.push("| # | Source | Target | Similarity |");
    lines.push("| --- | --- | --- | --- |");
    pairs.forEach((p, i) => {
      const src = p.source.length > 80 ? p.source.slice(0, 77) + "..." : p.source;
      const tgt = p.target.length > 80 ? p.target.slice(0, 77) + "..." : p.target;
      lines.push(`| ${i + 1} | ${src} | ${tgt} | ${((p.similarity || 0) * 100).toFixed(1)}% |`);
    });
    lines.push("");
  }

  if (aiResults && Object.keys(aiResults).length > 0) {
    lines.push("## AI Analysis");
    lines.push("");
    for (const [label, content] of Object.entries(aiResults)) {
      if (!content) continue;
      lines.push(`### ${label}`);
      lines.push("");
      lines.push(content);
      lines.push("");
    }
  }

  if (extraSections && extraSections.length > 0) {
    for (const section of extraSections) {
      lines.push(`## ${section.heading}`);
      lines.push("");
      lines.push(section.content);
      lines.push("");
    }
  }

  lines.push("---");
  lines.push("");
  lines.push("*Generated by Traduxa — Corpus Compilation & Analysis Lab for Translation Studies*");

  return lines.join("\n");
}

interface ParsedBlock {
  type: "h1" | "h2" | "h3" | "paragraph" | "bullet" | "numbered" | "table" | "hr";
  text?: string;
  items?: string[];
  table?: { headers: string[]; rows: string[][] };
}

function parseMarkdownToBlocks(markdown: string): ParsedBlock[] {
  const blocks: ParsedBlock[] = [];
  const lines = markdown.split("\n");
  let i = 0;

  while (i < lines.length) {
    const line = lines[i];
    const trimmed = line.trim();

    if (!trimmed) { i++; continue; }

    if (trimmed === "---" || trimmed === "***" || trimmed === "___") {
      blocks.push({ type: "hr" });
      i++;
      continue;
    }

    if (trimmed.startsWith("### ")) {
      blocks.push({ type: "h3", text: trimmed.slice(4).trim() });
      i++;
      continue;
    }
    if (trimmed.startsWith("## ")) {
      blocks.push({ type: "h2", text: trimmed.slice(3).trim() });
      i++;
      continue;
    }
    if (trimmed.startsWith("# ")) {
      blocks.push({ type: "h1", text: trimmed.slice(2).trim() });
      i++;
      continue;
    }

    if (trimmed.startsWith("|") && trimmed.endsWith("|")) {
      const separatorLine = (lines[i + 1] || "").trim();
      if (separatorLine.startsWith("|") && separatorLine.includes("-")) {
        const headers = trimmed.split("|").filter(Boolean).map(s => s.trim());
        const rows: string[][] = [];
        let j = i + 2;
        while (j < lines.length) {
          const rowLine = lines[j].trim();
          if (!rowLine.startsWith("|") || !rowLine.endsWith("|")) break;
          rows.push(rowLine.split("|").filter(Boolean).map(s => s.trim()));
          j++;
        }
        blocks.push({ type: "table", table: { headers, rows } });
        i = j;
        continue;
      }
    }

    if (/^[-*+]\s/.test(trimmed)) {
      const items: string[] = [];
      while (i < lines.length && /^[-*+]\s/.test(lines[i].trim())) {
        items.push(lines[i].trim().replace(/^[-*+]\s+/, ""));
        i++;
      }
      blocks.push({ type: "bullet", items });
      continue;
    }

    if (/^\d+[.)]\s/.test(trimmed)) {
      const items: string[] = [];
      while (i < lines.length && /^\d+[.)]\s/.test(lines[i].trim())) {
        items.push(lines[i].trim().replace(/^\d+[.)]\s+/, ""));
        i++;
      }
      blocks.push({ type: "numbered", items });
      continue;
    }

    let paragraphText = trimmed;
    i++;
    while (i < lines.length && lines[i].trim() && !lines[i].trim().startsWith("#") && !lines[i].trim().startsWith("|") && !/^[-*+]\s/.test(lines[i].trim()) && !/^\d+[.)]\s/.test(lines[i].trim()) && lines[i].trim() !== "---") {
      paragraphText += " " + lines[i].trim();
      i++;
    }
    blocks.push({ type: "paragraph", text: paragraphText });
  }

  return blocks;
}

function stripMarkdownFormatting(text: string): string {
  return text
    .replace(/\*\*(.*?)\*\*/g, "$1")
    .replace(/\*(.*?)\*/g, "$1")
    .replace(/`(.*?)`/g, "$1")
    .replace(/\[(.*?)\]\(.*?\)/g, "$1");
}

function createRichTextRuns(text: string, docx: any, baseSize: number = 22, baseFont: string = "Calibri"): any[] {
  const runs: any[] = [];
  const parts = text.split(/(\*\*.*?\*\*|\*.*?\*|`.*?`)/g);

  for (const part of parts) {
    if (!part) continue;
    if (part.startsWith("**") && part.endsWith("**")) {
      runs.push(new docx.TextRun({ text: part.slice(2, -2), bold: true, font: baseFont, size: baseSize }));
    } else if (part.startsWith("*") && part.endsWith("*")) {
      runs.push(new docx.TextRun({ text: part.slice(1, -1), italics: true, font: baseFont, size: baseSize }));
    } else if (part.startsWith("`") && part.endsWith("`")) {
      runs.push(new docx.TextRun({ text: part.slice(1, -1), font: "Consolas", size: baseSize - 2 }));
    } else {
      runs.push(new docx.TextRun({ text: part, font: baseFont, size: baseSize }));
    }
  }

  return runs;
}

async function generateWord(markdown: string, filename: string) {
  const docx = await import("docx");
  const { saveAs } = await import("file-saver");

  const blocks = parseMarkdownToBlocks(markdown);
  const children: any[] = [];

  children.push(
    new docx.Paragraph({
      children: [new docx.TextRun({
        text: "Traduxa",
        bold: true,
        font: "Calibri",
        size: 40,
        color: "1e3a5f",
      })],
      spacing: { after: 40 },
    })
  );
  children.push(
    new docx.Paragraph({
      children: [new docx.TextRun({
        text: "Corpus Compilation & Analysis Lab for Translation Studies",
        font: "Calibri",
        size: 18,
        italics: true,
        color: "6b7280",
      })],
      spacing: { after: 200 },
      border: { bottom: { style: docx.BorderStyle.SINGLE, size: 6, color: "e2e8f0" } },
    })
  );
  children.push(new docx.Paragraph({ children: [], spacing: { after: 100 } }));

  for (const block of blocks) {
    switch (block.type) {
      case "h1":
        children.push(new docx.Paragraph({
          children: [new docx.TextRun({
            text: stripMarkdownFormatting(block.text || ""),
            bold: true,
            font: "Calibri",
            size: 32,
            color: "1e3a5f",
          })],
          spacing: { before: 300, after: 120 },
        }));
        break;

      case "h2":
        children.push(new docx.Paragraph({
          children: [new docx.TextRun({
            text: stripMarkdownFormatting(block.text || ""),
            bold: true,
            font: "Calibri",
            size: 28,
            color: "2d4a6f",
          })],
          spacing: { before: 240, after: 100 },
        }));
        break;

      case "h3":
        children.push(new docx.Paragraph({
          children: [new docx.TextRun({
            text: stripMarkdownFormatting(block.text || ""),
            bold: true,
            font: "Calibri",
            size: 24,
            color: "374151",
          })],
          spacing: { before: 200, after: 80 },
        }));
        break;

      case "paragraph":
        children.push(new docx.Paragraph({
          children: createRichTextRuns(block.text || "", docx, 22),
          spacing: { after: 120 },
        }));
        break;

      case "bullet":
        for (const item of (block.items || [])) {
          children.push(new docx.Paragraph({
            children: createRichTextRuns(item, docx, 22),
            bullet: { level: 0 },
            spacing: { after: 60 },
          }));
        }
        break;

      case "numbered":
        for (const item of (block.items || [])) {
          children.push(new docx.Paragraph({
            children: createRichTextRuns(item, docx, 22),
            numbering: { reference: "default-numbering", level: 0 },
            spacing: { after: 60 },
          }));
        }
        break;

      case "hr":
        children.push(new docx.Paragraph({
          children: [],
          border: { bottom: { style: docx.BorderStyle.SINGLE, size: 4, color: "d1d5db" } },
          spacing: { before: 150, after: 150 },
        }));
        break;

      case "table":
        if (block.table) {
          const headerRow = new docx.TableRow({
            tableHeader: true,
            height: { value: 400, rule: docx.HeightRule.ATLEAST },
            children: block.table.headers.map(h =>
              new docx.TableCell({
                shading: { fill: "1e3a5f", type: docx.ShadingType.CLEAR },
                margins: { top: 60, bottom: 60, left: 100, right: 100 },
                children: [new docx.Paragraph({
                  children: [new docx.TextRun({
                    text: stripMarkdownFormatting(h),
                    bold: true,
                    color: "ffffff",
                    font: "Calibri",
                    size: 20,
                  })],
                })],
                verticalAlign: docx.VerticalAlign.CENTER,
              })
            ),
          });

          const dataRows = block.table.rows.map((row, idx) =>
            new docx.TableRow({
              height: { value: 360, rule: docx.HeightRule.ATLEAST },
              children: block.table!.headers.map((_, ci) =>
                new docx.TableCell({
                  shading: idx % 2 === 0
                    ? { fill: "f8fafc", type: docx.ShadingType.CLEAR }
                    : { fill: "ffffff", type: docx.ShadingType.CLEAR },
                  margins: { top: 50, bottom: 50, left: 100, right: 100 },
                  children: [new docx.Paragraph({
                    children: createRichTextRuns(row[ci] || "", docx, 20),
                  })],
                  verticalAlign: docx.VerticalAlign.CENTER,
                })
              ),
            })
          );

          children.push(new docx.Paragraph({ children: [], spacing: { after: 80 } }));
          children.push(new docx.Table({
            rows: [headerRow, ...dataRows],
            width: { size: 100, type: docx.WidthType.PERCENTAGE },
          }));
          children.push(new docx.Paragraph({ children: [], spacing: { after: 120 } }));
        }
        break;
    }
  }

  children.push(new docx.Paragraph({ children: [], spacing: { before: 200 } }));
  children.push(new docx.Paragraph({
    children: [new docx.TextRun({
      text: "Generated by Traduxa — Corpus Compilation & Analysis Lab for Translation Studies",
      font: "Calibri",
      size: 16,
      italics: true,
      color: "9ca3af",
    })],
    border: { top: { style: docx.BorderStyle.SINGLE, size: 4, color: "e2e8f0" } },
    spacing: { before: 200 },
  }));

  const doc = new docx.Document({
    numbering: {
      config: [{
        reference: "default-numbering",
        levels: [{
          level: 0,
          format: docx.LevelFormat.DECIMAL,
          text: "%1.",
          alignment: docx.AlignmentType.START,
        }],
      }],
    },
    sections: [{
      properties: {
        page: {
          margin: { top: 1440, bottom: 1440, left: 1440, right: 1440 },
        },
      },
      children,
    }],
  });

  const blob = await docx.Packer.toBlob(doc);
  saveAs(blob, `${filename}.docx`);
}

async function generatePDF(markdown: string, filename: string) {
  const html2canvas = (await import("html2canvas")).default;

  const blocks = parseMarkdownToBlocks(markdown);
  const container = document.createElement("div");
  container.style.cssText = "position:fixed;left:-9999px;top:0;width:800px;padding:48px;background:#fff;font-family:Calibri,Arial,sans-serif;color:#1a1a1a;line-height:1.6;font-size:14px;";

  let html = `<div style="border-bottom:2px solid #e2e8f0;padding-bottom:16px;margin-bottom:24px;">
    <h1 style="font-size:28px;color:#1e3a5f;margin:0 0 4px 0;font-weight:700;">Traduxa</h1>
    <p style="font-size:12px;color:#6b7280;margin:0 0 8px 0;font-style:italic;">Corpus Compilation & Analysis Lab for Translation Studies</p>
  </div>`;

  for (const block of blocks) {
    switch (block.type) {
      case "h1":
        html += `<h1 style="font-size:22px;color:#1e3a5f;margin:20px 0 8px;font-weight:700;">${stripMarkdownFormatting(block.text || "")}</h1>`;
        break;
      case "h2":
        html += `<h2 style="font-size:18px;color:#2d4a6f;margin:16px 0 6px;font-weight:700;">${stripMarkdownFormatting(block.text || "")}</h2>`;
        break;
      case "h3":
        html += `<h3 style="font-size:15px;color:#374151;margin:14px 0 6px;font-weight:600;">${stripMarkdownFormatting(block.text || "")}</h3>`;
        break;
      case "paragraph": {
        let t = block.text || "";
        t = t.replace(/\*\*(.*?)\*\*/g, '<strong>$1</strong>').replace(/\*(.*?)\*/g, '<em>$1</em>');
        html += `<p style="margin:0 0 10px;line-height:1.7;">${t}</p>`;
        break;
      }
      case "bullet":
        html += `<ul style="margin:0 0 10px;padding-left:24px;">`;
        for (const item of (block.items || [])) {
          let t = item.replace(/\*\*(.*?)\*\*/g, '<strong>$1</strong>').replace(/\*(.*?)\*/g, '<em>$1</em>');
          html += `<li style="margin:0 0 4px;">${t}</li>`;
        }
        html += `</ul>`;
        break;
      case "numbered":
        html += `<ol style="margin:0 0 10px;padding-left:24px;">`;
        for (const item of (block.items || [])) {
          let t = item.replace(/\*\*(.*?)\*\*/g, '<strong>$1</strong>').replace(/\*(.*?)\*/g, '<em>$1</em>');
          html += `<li style="margin:0 0 4px;">${t}</li>`;
        }
        html += `</ol>`;
        break;
      case "hr":
        html += `<hr style="border:none;border-top:1px solid #d1d5db;margin:16px 0;">`;
        break;
      case "table":
        if (block.table) {
          html += `<table style="width:100%;border-collapse:collapse;margin:12px 0;font-size:13px;">`;
          html += `<thead><tr>`;
          for (const h of block.table.headers) {
            html += `<th style="background:#1e3a5f;color:#fff;padding:8px 10px;text-align:left;font-size:11px;text-transform:uppercase;letter-spacing:0.5px;font-weight:600;">${stripMarkdownFormatting(h)}</th>`;
          }
          html += `</tr></thead><tbody>`;
          for (let ri = 0; ri < block.table.rows.length; ri++) {
            const bg = ri % 2 === 0 ? "#f8fafc" : "#ffffff";
            html += `<tr>`;
            for (let ci = 0; ci < block.table.headers.length; ci++) {
              let cellText = (block.table.rows[ri][ci] || "").replace(/\*\*(.*?)\*\*/g, '<strong>$1</strong>');
              html += `<td style="padding:7px 10px;border-bottom:1px solid #e5e7eb;background:${bg};">${cellText}</td>`;
            }
            html += `</tr>`;
          }
          html += `</tbody></table>`;
        }
        break;
    }
  }

  html += `<div style="border-top:1px solid #e2e8f0;margin-top:24px;padding-top:10px;">
    <p style="font-size:11px;color:#9ca3af;font-style:italic;margin:0;">Generated by Traduxa — Corpus Compilation & Analysis Lab for Translation Studies</p>
  </div>`;

  container.innerHTML = html;
  document.body.appendChild(container);

  try {
    const canvas = await html2canvas(container, { scale: 2, useCORS: true, backgroundColor: "#ffffff" });
    document.body.removeChild(container);

    const imgWidth = 595.28;
    const pageHeight = 841.89;
    const margin = 0;
    const contentWidth = imgWidth - margin * 2;
    const imgHeight = (canvas.height * contentWidth) / canvas.width;

    const { jsPDF } = await import("jspdf");
    const pdf = new jsPDF("p", "pt", "a4");

    let position = 0;
    let remainingHeight = imgHeight;
    const pageContentHeight = pageHeight - margin * 2;

    while (remainingHeight > 0) {
      if (position > 0) pdf.addPage();

      const sourceY = (position * canvas.width) / contentWidth;
      const sourceHeight = Math.min((pageContentHeight * canvas.width) / contentWidth, canvas.height - sourceY);

      const pageCanvas = document.createElement("canvas");
      pageCanvas.width = canvas.width;
      pageCanvas.height = sourceHeight;
      const ctx = pageCanvas.getContext("2d");
      if (ctx) {
        ctx.fillStyle = "#ffffff";
        ctx.fillRect(0, 0, pageCanvas.width, pageCanvas.height);
        ctx.drawImage(canvas, 0, sourceY, canvas.width, sourceHeight, 0, 0, canvas.width, sourceHeight);
      }

      const pageImgData = pageCanvas.toDataURL("image/jpeg", 0.95);
      const drawHeight = (sourceHeight * contentWidth) / canvas.width;
      pdf.addImage(pageImgData, "JPEG", margin, margin, contentWidth, drawHeight);

      position += pageContentHeight;
      remainingHeight -= pageContentHeight;
    }

    pdf.save(`${filename}.pdf`);
  } catch {
    document.body.removeChild(container);
  }
}

export function ReportGenerator(props: ReportGeneratorProps) {
  const [generatingWord, setGeneratingWord] = useState(false);
  const [generatingPDF, setGeneratingPDF] = useState(false);

  const filename = (props.title || "Traduxa_Report").replace(/\s+/g, "_");

  const handleWord = async () => {
    setGeneratingWord(true);
    try {
      const md = buildReportMarkdown(props);
      await generateWord(md, filename);
    } finally {
      setGeneratingWord(false);
    }
  };

  const handlePDF = async () => {
    setGeneratingPDF(true);
    try {
      const md = buildReportMarkdown(props);
      await generatePDF(md, filename);
    } finally {
      setGeneratingPDF(false);
    }
  };

  const hasData = props.stats || (props.keywords && props.keywords.length > 0) ||
    (props.collocations && props.collocations.length > 0) ||
    (props.ngrams && props.ngrams.length > 0) ||
    (props.aiResults && Object.keys(props.aiResults).length > 0) ||
    (props.pairs && props.pairs.length > 0) ||
    (props.extraSections && props.extraSections.length > 0);

  if (!hasData) return null;

  return (
    <div className="flex gap-1.5" data-testid="report-generator-buttons">
      <Button
        variant="ghost"
        size="sm"
        onClick={handleWord}
        disabled={generatingWord}
        data-testid="button-report-word"
      >
        {generatingWord ? <Loader2 className="w-3.5 h-3.5 mr-1.5 animate-spin" /> : <FileText className="w-3.5 h-3.5 mr-1.5" />}
        Full Report (Word)
      </Button>
      <Button
        variant="ghost"
        size="sm"
        onClick={handlePDF}
        disabled={generatingPDF}
        data-testid="button-report-pdf"
      >
        {generatingPDF ? <Loader2 className="w-3.5 h-3.5 mr-1.5 animate-spin" /> : <FileDown className="w-3.5 h-3.5 mr-1.5" />}
        Full Report (PDF)
      </Button>
    </div>
  );
}
