import { db } from "./db";
import { libraryCorpora, type InsertLibraryCorpus, type LibraryCorpus } from "@shared/schema";
import { eq, desc, inArray } from "drizzle-orm";

export async function getLibraryCorpora(): Promise<LibraryCorpus[]> {
  return db.select().from(libraryCorpora).orderBy(desc(libraryCorpora.createdAt));
}

export async function getLibraryCorpus(id: number): Promise<LibraryCorpus | undefined> {
  const rows = await db.select().from(libraryCorpora).where(eq(libraryCorpora.id, id));
  return rows[0];
}

export async function saveLibraryCorpus(data: InsertLibraryCorpus): Promise<LibraryCorpus> {
  const rows = await db.insert(libraryCorpora).values(data).returning();
  return rows[0];
}

export async function deleteLibraryCorpus(id: number): Promise<void> {
  await db.delete(libraryCorpora).where(eq(libraryCorpora.id, id));
}

